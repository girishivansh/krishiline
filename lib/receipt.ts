import { grossFor, hamaliFor, netFor, GRADE_LABEL, type Booking } from "./data";

export function escapeHtml(str: string | number | null | undefined): string {
  if (str === null || str === undefined) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export function receiptHtml(b: Booking) {
  const safeReceiptId = escapeHtml(b.receiptId ?? b.token);
  const safeReceiptDisplay = escapeHtml(b.receiptId ?? "Pending — issued after grading");
  const safeBatchNo = escapeHtml(b.batchNo);
  const safeToken = escapeHtml(b.token);
  const safeFarmer = escapeHtml(b.farmer);
  const safeVillage = escapeHtml(b.village);
  const safeDisplayDate = escapeHtml(b.displayDate);
  const safeSlot = escapeHtml(b.slot);
  const safeCentre = escapeHtml(b.centre);
  const safeCrop = escapeHtml(b.crop);
  const safeGrade = escapeHtml(GRADE_LABEL[b.grade]);
  const safeStatus = escapeHtml(b.status);
  const safePaymentStatus = escapeHtml(b.paymentStatus);
  const safeQty = escapeHtml(b.quantityKg.toLocaleString("en-IN"));
  const safeQuintals = escapeHtml((b.quantityKg / 100).toLocaleString("en-IN"));
  const safeRate = escapeHtml(b.pricePerQuintal.toLocaleString("en-IN"));
  const safeGross = escapeHtml(grossFor(b).toLocaleString("en-IN"));
  const safeHamali = escapeHtml(hamaliFor(b).toLocaleString("en-IN"));
  const safeNet = escapeHtml(netFor(b).toLocaleString("en-IN"));

  return `<!doctype html><html><head><meta charset="utf-8"><title>Receipt ${safeReceiptId}</title><style>body{font-family:Arial,sans-serif;max-width:640px;margin:40px auto;padding:24px;border:1px solid #ccc;border-radius:12px}h1{color:#065f46;margin-top:0}table{width:100%;border-collapse:collapse}td{padding:8px;border-bottom:1px solid #eee}.total{font-weight:bold;font-size:18px;color:#065f46}.official{color:#065f46;background:#ecfdf5;border:1px solid #a7f3d0;padding:10px;border-radius:6px;font-size:13px;font-weight:600}</style></head><body><h1>Krishi-Line — Digital Intake Receipt</h1><p class="official">OFFICIAL INTAKE RECEIPT — Generated by Krishi-Line Mandi Procurement Node.</p><table><tr><td>Receipt ID</td><td>${safeReceiptDisplay}</td></tr><tr><td>Batch No.</td><td>${safeBatchNo}</td></tr><tr><td>QR Token</td><td>${safeToken}</td></tr><tr><td>Farmer</td><td>${safeFarmer}, ${safeVillage}, Nashik</td></tr><tr><td>Date / Slot</td><td>${safeDisplayDate} · ${safeSlot}</td></tr><tr><td>Centre</td><td>${safeCentre}</td></tr><tr><td>Crop / Grade</td><td>${safeCrop} / ${safeGrade}</td></tr><tr><td>Quantity</td><td>${safeQty} kg (${safeQuintals} quintals)</td></tr><tr><td>Rate</td><td>₹${safeRate} / quintal</td></tr><tr><td>Gross Amount</td><td>₹${safeGross}</td></tr><tr><td>Hamali Deduction</td><td>− ₹${safeHamali}</td></tr><tr><td>Other Deductions</td><td>− ₹200</td></tr><tr><td class="total">Net Payable</td><td class="total">₹${safeNet}</td></tr><tr><td>Status</td><td>${safeStatus} · Payment: ${safePaymentStatus}</td></tr></table><p style="font-size:12px;color:#6b7280;margin-top:16px;">Verify a receipt by matching its token, batch number and receipt ID with the booking in the Farmer Portal.</p></body></html>`;
}

export function downloadReceipt(b: Booking) {
  const blob = new Blob([receiptHtml(b)], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  const rawId = b.receiptId ?? b.token;
  const safeFilename = `${rawId.replace(/[^a-zA-Z0-9_-]/g, "_")}-receipt.html`;
  a.href = url;
  a.download = safeFilename;
  a.click();
  URL.revokeObjectURL(url);
}
